-- =====================================================
-- 1. TABELA DE USUÁRIOS (COMPRADORES, VENDEDORES E ADMINS)
-- =====================================================

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    senha VARCHAR(150) NOT NULL,
    vendedor BOOLEAN DEFAULT FALSE,
    admin BOOLEAN DEFAULT FALSE,
    perfil VARCHAR(50) DEFAULT 'comprador',
    propriedade VARCHAR(150),
    municipio VARCHAR(150),
    tipo_documento VARCHAR(20),
    documento VARCHAR(50),
    data_nascimento VARCHAR(30),
    telefone VARCHAR(50),
    cep VARCHAR(30),
    endereco TEXT,
    tipo_producao VARCHAR(100),
    descricao_atividade TEXT,
    arquivo_documento VARCHAR(255),
    foto_perfil TEXT,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 2. TABELA DE PRODUTOS
-- =====================================================

CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    nome VARCHAR(200) NOT NULL,
    tipo VARCHAR(100) NOT NULL,
    quantidade VARCHAR(100) NOT NULL,
    preco VARCHAR(100) NOT NULL,
    localizacao VARCHAR(150) NOT NULL,
    emoji VARCHAR(20) DEFAULT '🌱',
    descricao TEXT,
    unidade VARCHAR(50),
    pedido_minimo VARCHAR(100),
    foto TEXT,
    disponivel BOOLEAN DEFAULT TRUE,
    vendedor_nome VARCHAR(150),
    vendedor_email VARCHAR(150),
    avaliacoes JSONB DEFAULT '[]'::jsonb,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_produto_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE SET NULL
);


-- =====================================================
-- 3. TABELA DE COLHEITAS (PREVISÕES DE SAFRA)
-- =====================================================

CREATE TABLE colheitas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    produto VARCHAR(200) NOT NULL,
    quantidade VARCHAR(100) NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    status VARCHAR(50) DEFAULT 'Prevista',
    observacoes TEXT,
    vendedor_nome VARCHAR(150),
    vendedor_email VARCHAR(150),
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_colheita_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE SET NULL
);


-- =====================================================
-- 4. TABELA DE PEDIDOS E NEGOCIAÇÕES
-- =====================================================

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT,
    comprador_id BIGINT,
    vendedor_id BIGINT,
    produto_nome VARCHAR(200) NOT NULL,
    quantidade VARCHAR(100) NOT NULL,
    quantidade_valor NUMERIC(12, 3),
    quantidade_unidade VARCHAR(50),
    quantidade_disponivel VARCHAR(100),
    comprador_nome VARCHAR(150),
    comprador_email VARCHAR(150),
    vendedor_nome VARCHAR(150),
    vendedor_email VARCHAR(150),
    data_pedido VARCHAR(30),
    status VARCHAR(50) DEFAULT 'Negociação',
    forma_entrega VARCHAR(100) DEFAULT 'A combinar',
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedido_produto
        FOREIGN KEY (produto_id)
        REFERENCES produtos(id)
        ON DELETE SET NULL,
    CONSTRAINT fk_pedido_comprador
        FOREIGN KEY (comprador_id)
        REFERENCES usuarios(id)
        ON DELETE SET NULL,
    CONSTRAINT fk_pedido_vendedor
        FOREIGN KEY (vendedor_id)
        REFERENCES usuarios(id)
        ON DELETE SET NULL
);


-- =====================================================
-- 5. TABELA DE TRANSPORTES E LOGÍSTICA
-- =====================================================

CREATE TABLE transportes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    placa VARCHAR(30),
    produto VARCHAR(200) NOT NULL,
    origem VARCHAR(150) NOT NULL,
    destino VARCHAR(150) NOT NULL,
    quantidade VARCHAR(100) NOT NULL,
    status VARCHAR(50) DEFAULT 'Solicitado',
    vendedor_email VARCHAR(150),
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_transporte_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE SET NULL
);


-- =====================================================
-- 6. TABELA DE SOBRAS E DESPERDÍCIOS
-- =====================================================

CREATE TABLE sobras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    produto VARCHAR(200) NOT NULL,
    quantidade VARCHAR(100) NOT NULL,
    destino VARCHAR(50) NOT NULL,
    data_registro VARCHAR(30) NOT NULL,
    vendedor_email VARCHAR(150),
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sobra_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE SET NULL
);


-- =====================================================
-- 7. TABELA DE INTERESSES DO COMPRADOR
-- =====================================================

CREATE TABLE interesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT,
    usuario_id BIGINT,
    comprador_email VARCHAR(150) NOT NULL,
    nome VARCHAR(200) NOT NULL,
    tipo VARCHAR(100),
    preco VARCHAR(100),
    quantidade VARCHAR(100),
    unidade VARCHAR(50),
    vendedor_nome VARCHAR(150),
    vendedor_email VARCHAR(150),
    localizacao VARCHAR(150),
    foto TEXT,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_interesse_produto
        FOREIGN KEY (produto_id)
        REFERENCES produtos(id)
        ON DELETE CASCADE,
    CONSTRAINT fk_interesse_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuarios(id)
        ON DELETE CASCADE
);


-- =====================================================
-- 8. TABELA DE MENSAGENS (CHAT)
-- =====================================================

CREATE TABLE mensagens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    remetente_id BIGINT,
    destinatario_id BIGINT,
    conversa_chave VARCHAR(320) NOT NULL,
    remetente_email VARCHAR(150) NOT NULL,
    destinatario_email VARCHAR(150) NOT NULL,
    texto TEXT NOT NULL,
    lida BOOLEAN DEFAULT FALSE,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mensagem_remetente
        FOREIGN KEY (remetente_id)
        REFERENCES usuarios(id)
        ON DELETE SET NULL,
    CONSTRAINT fk_mensagem_destinatario
        FOREIGN KEY (destinatario_id)
        REFERENCES usuarios(id)
        ON DELETE SET NULL
);


